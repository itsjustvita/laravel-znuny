<?php

namespace ItsJustVita\LaravelZnuny\Commands;

use Illuminate\Console\Command;
use InvalidArgumentException;
use ItsJustVita\LaravelZnuny\Exceptions\ZnunyConfigurationException;
use ItsJustVita\LaravelZnuny\Routing\RouteMap;
use ItsJustVita\LaravelZnuny\Support\Yaml;
use ItsJustVita\LaravelZnuny\WebService\WebServiceDefinition;
use Symfony\Component\Console\Output\OutputInterface;

class WebServiceCommand extends Command
{
    protected $signature = 'znuny:webservice
        {connection? : Connection name (defaults to the default connection)}
        {--routes= : A route preset to use instead of the routes of the connection}
        {--webhooks= : Comma-separated ticket events to send to this application, e.g. TicketCreate,ArticleCreate}
        {--webhook-url= : Base URL of this application as Znuny reaches it (defaults to app.url)}
        {--with-token : Write the webhook secret into the file}
        {--sync : Deliver webhooks synchronously instead of through the Znuny daemon}
        {--output= : Write the definition to this file instead of printing it}';

    protected $description = 'Generate the Znuny web service definition for a connection, optionally with webhooks';

    public function handle(): int
    {
        $name = (string) ($this->argument('connection') ?? config('znuny.default', 'default'));
        $preset = $this->option('routes');
        $connection = config("znuny.connections.{$name}");

        if (! is_string($preset) && ! is_array($connection)) {
            $this->error("Znuny connection [{$name}] is not configured. Pass --routes=<preset> to generate the web service for a route preset.");

            return self::FAILURE;
        }

        try {
            $routes = RouteMap::fromConfig(is_string($preset) ? $preset : ($connection['routes'] ?? null));
        } catch (ZnunyConfigurationException $e) {
            $this->error($e->getMessage());

            return self::FAILURE;
        }

        $definition = WebServiceDefinition::fromRoutes($routes);
        $comments = ['# Generated by laravel-znuny (php artisan znuny:webservice).'];

        if ($definition->skipped() !== []) {
            $comments[] = '# Left out, because they are no Znuny core operations: '.implode(', ', $definition->skipped()).'.';
        }

        $webhooks = $this->option('webhooks');
        $events = is_string($webhooks) ? array_values(array_filter(array_map('trim', explode(',', $webhooks)))) : [];
        $endpoint = null;

        if ($events !== []) {
            $url = (string) ($this->option('webhook-url') ?: config('app.url'));

            if ($url === '') {
                $this->error('Pass --webhook-url with the URL under which Znuny reaches this application, or set app.url.');

                return self::FAILURE;
            }

            $prefix = (string) config('znuny.webhooks.route_prefix', 'znuny/webhooks');
            $endpoint = rtrim($url, '/').'/'.trim($prefix, '/');
            $host = strtolower(trim((string) parse_url($url, PHP_URL_HOST), '[]'));

            if (self::isOwnMachine($host)) {
                $comments[] = "# The webhook host {$host} points to the machine Znuny runs on. Unless this application runs there too, pass --webhook-url with an address Znuny can reach.";
            }

            $auth = (array) config('znuny.webhooks.auth', []);
            $withSecrets = (bool) $this->option('with-token');

            $definition = $definition->withWebhooks(
                $events,
                $url,
                $prefix,
                $auth,
                $withSecrets,
                (bool) $this->option('sync'),
            );

            if (! $withSecrets && in_array(strtolower((string) ($auth['type'] ?? 'token')), ['token', 'basic'], true)) {
                $comments[] = '# Replace '.WebServiceDefinition::PLACEHOLDER.' with the webhook secret before the import, or generate the file with --with-token.';
            }
        }

        try {
            $yaml = implode("\n", $comments)."\n".Yaml::dump($definition->toArray());
        } catch (InvalidArgumentException $e) {
            $this->error($e->getMessage());
            $this->line('Check the encoding of the setting it comes from, for example in your .env file.');

            return self::FAILURE;
        }

        $output = $this->option('output');

        if (! is_string($output) || $output === '') {
            $this->getOutput()->write($yaml, false, OutputInterface::OUTPUT_RAW);

            return self::SUCCESS;
        }

        if (@file_put_contents($output, $yaml) === false) {
            $this->error("Could not write [{$output}].");

            return self::FAILURE;
        }

        $this->info("Wrote the web service definition to [{$output}].");
        $this->line('Import it in Znuny under Admin → Web Services → Add Web Service → Import web service, or on the Znuny server with:');
        $this->line("  bin/otrs.Console.pl Admin::WebService::Add --name <name> --source-path {$output}");

        if ($endpoint !== null) {
            $this->line("Znuny will send webhooks to [{$endpoint}].");
        }

        foreach (array_slice($comments, 1) as $comment) {
            $this->warn(ltrim($comment, '# '));
        }

        return self::SUCCESS;
    }

    /**
     * Whether a host means the machine Znuny runs on, as seen from Znuny: localhost,
     * *.localhost and the loopback and unspecified addresses.
     */
    private static function isOwnMachine(string $host): bool
    {
        if ($host === 'localhost' || str_ends_with($host, '.localhost')) {
            return true;
        }

        return filter_var($host, FILTER_VALIDATE_IP) !== false
            && (str_starts_with($host, '127.') || in_array($host, ['::1', '0.0.0.0'], true));
    }
}
